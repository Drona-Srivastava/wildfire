function modelFile = build_ignis_sim()
%BUILD_IGNIS_SIM Build the first executable Simulink wildfire/UAV model.
% Grid: 40x40 cells at 10 m/cell; x=east, y=north; fire update time=1 s.
% Fire spread is an illustrative cellular automaton, not a physical model.

root = fileparts(fileparts(mfilename('fullpath')));
modelDir = fullfile(root, 'simulation');
modelName = 'ignis_wildfire_uav';
modelFile = fullfile(modelDir, [modelName '.slx']);

% Create the in-memory model outside both the model folder and project root.
% MATLAB implicitly searches the current folder even when it is not on path,
% so rmpath(modelDir) alone cannot prevent the existing SLX from shadowing it.
previousPath = path;
previousFolder = pwd;
pathEntries = strsplit(previousPath, pathsep);
if any(strcmpi(pathEntries, modelDir)), rmpath(modelDir); end
if any(strcmpi(pathEntries, root)), rmpath(root); end
if bdIsLoaded(modelName)
    close_system(modelName, 0);
end
try
    cd(tempdir);
    new_system(modelName);
catch buildError
    cd(previousFolder);
    path(previousPath);
    rethrow(buildError);
end
cd(previousFolder);
path(previousPath);
addpath(modelDir);
load_system('simulink');
set_param(modelName, ...
    'Solver', 'FixedStepDiscrete', ...
    'FixedStep', '0.016666666666666666', ...
    'StopTime', '300', ...
    'SaveOutput', 'off', ...
    'SignalLogging', 'off', ...
    'ReturnWorkspaceOutputs', 'on', ...
    'Description', ['IGNIS-FORECAST milestone 1. ' ...
        'Illustrative 40x40 wildfire cellular automaton and waypoint UAV. ' ...
        'Grid is 10 m/cell; 3D solver is 60 Hz and fire spread updates once per second. ' ...
        'Fire spread is not calibrated.']);

add_block('simulink/Sources/Clock', [modelName '/Simulation time'], ...
    'Position', [35 110 75 130]);
add_constant(modelName, 'Wind direction (deg)', '0', [30 195 125 225]);
add_constant(modelName, 'Wind speed mps', '4', [30 250 125 280]);
add_constant(modelName, 'Relative humidity (%)', '40', [30 305 125 335]);
add_constant(modelName, 'Air temperature C', '32', [30 360 125 390]);
[mapX, mapY] = meshgrid(1:40, 1:40);
fuelMap = 0.55 + 0.35*(0.5 + 0.5*sin(mapX/6).*cos(mapY/8));
fuelMap(:,10:11) = 0.12; % illustrative low-fuel strip/firebreak
elevationMap = 220 + 24*sin(mapX/8).*cos(mapY/10) + 9*cos((mapX+mapY)/12);
add_constant(modelName, 'Fuel availability map', mat2str(fuelMap, 4), [30 415 125 445]);
add_constant(modelName, 'Terrain elevation map m', mat2str(elevationMap, 5), [30 470 125 500]);

