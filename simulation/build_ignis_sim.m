add_line(modelName, 'UAV waypoint controller/4', 'UAV ground speed (mps)/1');
add_line(modelName, 'UAV waypoint controller/5', 'UAV heading (deg)/1');
add_line(modelName, 'UAV waypoint controller/6', 'UAV battery (%)/1');
add_line(modelName, 'UAV waypoint controller/7', 'Current waypoint index/1');
add_line(modelName, 'UAV camera and fire report/1', 'Observed grid (255 = unknown)/1');
add_line(modelName, 'UAV camera and fire report/2', 'Burning cells in UAV camera footprint/1');
add_line(modelName, 'UAV camera and fire report/3', 'Burned cells in UAV camera footprint/1');
