    'next_ignition_row_log', [750 540 910 570]);
add_workspace_sink(modelName, 'Highest-risk cell column', ...
    'next_ignition_col_log', [750 580 910 610]);
add_workspace_sink(modelName, 'Highest next-ignition probability', ...
    'next_ignition_probability_log', [750 620 910 650]);
add_workspace_sink(modelName, 'UAV x (grid cells)', 'uav_x_log', [555 340 715 370]);
add_workspace_sink(modelName, 'UAV y (grid cells)', 'uav_y_log', [555 380 715 410]);
