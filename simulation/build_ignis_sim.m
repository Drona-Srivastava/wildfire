    'Position', [260 365 445 505]);
uavChart = stateflowRoot.find('-isa', 'Stateflow.EMChart', 'Path', uavBlock);
uavChart.Script = uav_code();

add_line(modelName, 'Simulation time/1', 'Fire cellular automaton/1');
add_line(modelName, 'Wind direction (deg)/1', 'Fire cellular automaton/2');
add_line(modelName, 'Wind speed mps/1', 'Fire cellular automaton/3');
