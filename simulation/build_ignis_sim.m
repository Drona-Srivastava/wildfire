save_system(modelName, modelFile);
close_system(modelName, 0);
if ~any(strcmpi(strsplit(path, pathsep), modelDir))
    addpath(modelDir);
end
build_ignis_uav_scene();
fprintf('Built Simulink model: %s\n', modelFile);
end

