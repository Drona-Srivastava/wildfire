function code = fire_code()
code = sprintf([ ...
    'function [fireState, affectedCells] = fire_ca(simTime, windDirDeg, windSpeed, rh, temperatureC, fuelMap, elevationMap)\n' ...
    '%%#codegen\n' ...
    'persistent state burnAge tick lastUpdateTime\n' ...
    'if isempty(state)\n' ...
    '    state = zeros(40,40,''uint8'');\n' ...
    '    state(20,20) = uint8(1);\n' ...
    '    burnAge = zeros(40,40,''uint8'');\n' ...
    '    tick = 0;\n' ...
    '    lastUpdateTime = -1.0;\n' ...
    'end\n' ...
    'if simTime - lastUpdateTime < 0.999999\n' ...
    '    fireState = state; affectedCells = double(sum(state(:) > 0)); return;\n' ...
    'end\n' ...
    'lastUpdateTime = simTime;\n' ...
    'tick = tick + 1;\n' ...
    'oldState = state;\n' ...
    'oldBurnAge = burnAge;\n' ...
    'newBurning = false(40,40);\n' ...
    'dryness = min(1.0, max(0.05, 1.0 - rh/100.0));\n' ...
    'windX = cosd(windDirDeg);\n' ...
    'windY = sind(windDirDeg);\n' ...
    'windGain = exp(0.025*max(0.0, windSpeed));\n' ...
    'temperatureGain = min(1.35, max(0.75, 1.0 + 0.015*(temperatureC - 25.0)));\n' ...
    'for row = 1:40\n' ...
    '    for col = 1:40\n' ...
    '        if oldState(row,col) ~= 0\n' ...
    '            continue;\n' ...
    '        end\n' ...
    '        neighbors = 0;\n' ...
    '        alignment = 0.0;\n' ...
    '        slopeAlignment = 0.0;\n' ...
    '        for dr = -1:1\n' ...
    '            for dc = -1:1\n' ...
    '                if dr == 0 && dc == 0\n' ...
    '                    continue;\n' ...
    '                end\n' ...
    '                rr = row + dr; cc = col + dc;\n' ...
    '                if rr >= 1 && rr <= 40 && cc >= 1 && cc <= 40 && oldState(rr,cc) == 1\n' ...
    '                    neighbors = neighbors + 1;\n' ...
    '                    normDir = sqrt(double(dr*dr + dc*dc));\n' ...
    '                    alignment = alignment + ((dc/normDir)*windX + (-dr/normDir)*windY);\n' ...
    '                    slopeAlignment = slopeAlignment + (elevationMap(row,col) - elevationMap(rr,cc))/10.0;\n' ...
    '                end\n' ...
    '            end\n' ...
    '        end\n' ...
    '        if neighbors > 0\n' ...
    '            baseRisk = 1.0 - exp(-0.12*neighbors);\n' ...
    '            windFactor = exp(0.10*min(1.0, max(-1.0, alignment/neighbors))*max(0.0,windSpeed));\n' ...
    '            slopeFactor = 1.0 + 0.25*tanh(slopeAlignment/neighbors);\n' ...
    '            fuelFactor = min(1.0, max(0.05, fuelMap(row,col)));\n' ...
    '            probability = min(0.95, baseRisk*dryness*windGain*windFactor*temperatureGain*fuelFactor*slopeFactor);\n' ...
    '            hashValue = mod(row*73856093 + col*19349663 + tick*83492791, 1000003)/1000003.0;\n' ...
    '            newBurning(row,col) = hashValue < probability;\n' ...
    '        end\n' ...
    '    end\n' ...
    'end\n' ...
    'for row = 1:40\n' ...
    '    for col = 1:40\n' ...
    '        if oldState(row,col) == 1\n' ...
    '            burnAge(row,col) = oldBurnAge(row,col) + uint8(1);\n' ...
    '            if burnAge(row,col) >= 15\n' ...
    '                state(row,col) = uint8(2); burnAge(row,col) = uint8(0);\n' ...
    '            end\n' ...
    '        end\n' ...
    '    end\n' ...
    'end\n' ...
    'state(newBurning) = uint8(1);\n' ...
    'burnAge(newBurning) = uint8(1);\n' ...
    'fireState = state;\n' ...
    'affectedCells = double(sum(state(:) > 0));\n' ...
    'end\n']);
end

function code = sensor_code()
code = sprintf([ ...
    'function [observedMap, burningSeen, burnedSeen, reportEvent, reportX, reportY, coverageCells] = survey(fireState, xCell, yCell, altitudeM, simTime, waypointObservation)\n' ...
    '%%#codegen\n' ...
    'observedMap = uint8(255*ones(40,40));\n' ...
    'radius = min(6.0, max(1.0, ceil(altitudeM*tand(30.0)/10.0)));\n' ...
    'burningSeen = 0.0; burnedSeen = 0.0; coverageCells = 0.0;\n' ...
    'sumX = 0.0; sumY = 0.0; sumBurnX = 0.0; sumBurnY = 0.0;\n' ...
    'for row = 1:40\n' ...
    '    northY = 41.0 - row;\n' ...
    '    for col = 1:40\n' ...
    '        if abs(double(col)-xCell) <= radius && abs(northY-yCell) <= radius\n' ...
    '            observedMap(row,col) = fireState(row,col);\n' ...
    '            coverageCells = coverageCells + 1.0;\n' ...
    '            if fireState(row,col) == 1\n' ...
    '                burningSeen = burningSeen + 1.0; sumX = sumX + col; sumY = sumY + northY;\n' ...
    '            elseif fireState(row,col) == 2\n' ...
    '                burnedSeen = burnedSeen + 1.0; sumBurnX = sumBurnX + col; sumBurnY = sumBurnY + northY;\n' ...
    '            end\n' ...
    '        end\n' ...
    '    end\n' ...
    'end\n' ...
    'reportEvent = double((burningSeen > 0.0 || burnedSeen > 0.0) && (waypointObservation > 0.0 || mod(floor(simTime),5.0) == 0.0));\n' ...
    'if burningSeen > 0.0\n' ...
    '    reportX = sumX/burningSeen; reportY = sumY/burningSeen;\n' ...
    'elseif burnedSeen > 0.0\n' ...
    '    reportX = sumBurnX/burnedSeen; reportY = sumBurnY/burnedSeen;\n' ...
    'else\n' ...
    '    reportX = -1.0; reportY = -1.0;\n' ...
    'end\n' ...
    'end\n']);
end

function code = forecast_code()
code = sprintf([ ...
    'function [riskMap,nextRow,nextCol,nextProbability] = forecast(fireState,windDirDeg,windSpeed,rh,temperatureC,fuelMap,elevationMap)\n' ...
    '%%#codegen\n' ...
    'riskMap = zeros(40,40); nextRow = -1.0; nextCol = -1.0; nextProbability = 0.0;\n' ...
    'dryness = min(1.0,max(0.05,1.0-rh/100.0));\n' ...
    'windX = cosd(windDirDeg); windY = sind(windDirDeg);\n' ...
    'windGain = exp(0.025*max(0.0,windSpeed));\n' ...
    'temperatureGain = min(1.35,max(0.75,1.0+0.015*(temperatureC-25.0)));\n' ...
    'for row = 1:40\n' ...
    '    for col = 1:40\n' ...
    '        if fireState(row,col) ~= 0, continue; end\n' ...
    '        neighbors = 0; alignment = 0.0; slopeAlignment = 0.0;\n' ...
    '        for dr = -1:1\n' ...
    '            for dc = -1:1\n' ...
    '                if dr == 0 && dc == 0, continue; end\n' ...
    '                rr = row+dr; cc = col+dc;\n' ...
    '                if rr>=1 && rr<=40 && cc>=1 && cc<=40 && fireState(rr,cc)==1\n' ...
    '                    neighbors = neighbors+1; normDir = sqrt(double(dr*dr+dc*dc));\n' ...
    '                    alignment = alignment+(dc/normDir*windX+(-dr/normDir)*windY);\n' ...
    '                    slopeAlignment = slopeAlignment+(elevationMap(row,col)-elevationMap(rr,cc))/10.0;\n' ...
    '                end\n' ...
    '            end\n' ...
    '        end\n' ...
    '        if neighbors>0\n' ...
    '            baseRisk = 1.0-exp(-0.12*neighbors);\n' ...
    '            windFactor = exp(0.10*min(1.0,max(-1.0,alignment/neighbors))*max(0.0,windSpeed));\n' ...
    '            slopeFactor = 1.0+0.25*tanh(slopeAlignment/neighbors);\n' ...
    '            fuelFactor = min(1.0,max(0.05,fuelMap(row,col)));\n' ...
    '            riskMap(row,col) = min(0.95,baseRisk*dryness*windGain*windFactor*temperatureGain*fuelFactor*slopeFactor);\n' ...
    '            if riskMap(row,col)>nextProbability\n' ...
    '                nextProbability = riskMap(row,col); nextRow = row; nextCol = col;\n' ...
    '            end\n' ...
    '        end\n' ...
    '    end\n' ...
    'end\n' ...
    'end\n']);
end

function code = uav_code()
code = sprintf([ ...
    'function [xCell, yCell, altitudeM, groundSpeedMps, headingDeg, batteryPct, waypointIndex, observe] = uav_step(simTime, windDirDeg, windSpeed)\n' ...
    '%%#codegen\n' ...
    'persistent x y battery wp lastSimTime\n' ...
    'if isempty(x)\n' ...
    '    x = 2.0; y = 2.0; battery = 100.0; wp = 1.0;\n' ...
    '    lastSimTime = simTime;\n' ...
    'end\n' ...
    'dt = max(0.0, simTime - lastSimTime); lastSimTime = simTime;\n' ...
    'waypointX = [5.0 35.0 20.0 35.0 5.0 20.0];\n' ...
    'waypointY = [5.0 5.0 20.0 35.0 35.0 5.0];\n' ...
    'if battery < 20.0\n' ...
    '    targetX = 1.0; targetY = 1.0;\n' ...
    'else\n' ...
    '    targetX = waypointX(int32(wp)); targetY = waypointY(int32(wp));\n' ...
    'end\n' ...
    'dx = targetX - x; dy = targetY - y; distance = sqrt(dx*dx + dy*dy);\n' ...
    'speedCellsPerSec = 0.8;\n' ...
    'if distance > 0.0\n' ...
    '    step = min(speedCellsPerSec*dt, distance);\n' ...
    '    vx = step*dx/distance; vy = step*dy/distance;\n' ...
    '    windX = 0.005*windSpeed*cosd(windDirDeg)*dt;\n' ...
    '    windY = 0.005*windSpeed*sind(windDirDeg)*dt;\n' ...
    '    actualVx = vx + windX; actualVy = vy + windY;\n' ...
    '    x = min(40.0, max(1.0, x + actualVx));\n' ...
    '    y = min(40.0, max(1.0, y + actualVy));\n' ...
    '    groundSpeedMps = 10.0*sqrt(actualVx*actualVx + actualVy*actualVy);\n' ...
    'else\n' ...
    '    groundSpeedMps = 0.0;\n' ...
    'end\n' ...
    'distance = sqrt((targetX-x)^2 + (targetY-y)^2);\n' ...
    'if battery >= 20.0 && distance < 0.7\n' ...
    '    wp = mod(wp,6.0) + 1.0;\n' ...
    'end\n' ...
    'battery = max(0.0, battery - (0.025 + 0.002*max(0.0,windSpeed))*dt);\n' ...
    'headingDeg = atan2d(dy,dx);\n' ...
    'xCell = x; yCell = y; altitudeM = 50.0; batteryPct = battery; waypointIndex = wp;\n' ...
    'observe = double(distance < 1.0 && mod(floor(simTime),5.0) == 0.0);\n' ...
    'end\n']);
end
