add_line(modelName, 'Fire cellular automaton/1', 'Weather-based next ignition forecast/1');
add_line(modelName, 'Wind direction (deg)/1', 'Weather-based next ignition forecast/2');
add_line(modelName, 'Wind speed mps/1', 'Weather-based next ignition forecast/3');
add_line(modelName, 'Relative humidity (%)/1', 'Weather-based next ignition forecast/4');
add_line(modelName, 'Air temperature C/1', 'Weather-based next ignition forecast/5');
add_line(modelName, 'Fuel availability map/1', 'Weather-based next ignition forecast/6');
add_line(modelName, 'Terrain elevation map m/1', 'Weather-based next ignition forecast/7');
add_line(modelName, 'Simulation time/1', 'UAV waypoint controller/1');
add_line(modelName, 'Wind direction (deg)/1', 'UAV waypoint controller/2');
add_line(modelName, 'Wind speed mps/1', 'UAV waypoint controller/3');

sensorBlock = [modelName '/UAV camera and fire report'];
add_block('simulink/User-Defined Functions/MATLAB Function', sensorBlock, ...
    'Position', [790 185 990 345]);
sensorChart = stateflowRoot.find('-isa', 'Stateflow.EMChart', 'Path', sensorBlock);
sensorChart.Script = sensor_code();
add_line(modelName, 'Fire cellular automaton/1', 'UAV camera and fire report/1');
add_line(modelName, 'UAV waypoint controller/1', 'UAV camera and fire report/2');
add_line(modelName, 'UAV waypoint controller/2', 'UAV camera and fire report/3');
add_line(modelName, 'UAV waypoint controller/3', 'UAV camera and fire report/4');
add_line(modelName, 'Simulation time/1', 'UAV camera and fire report/5');
add_line(modelName, 'UAV waypoint controller/8', 'UAV camera and fire report/6');

add_workspace_sink(modelName, 'Fire grid (0 unburned, 1 burning, 2 burned)', ...
    'fire_state_log', [555 175 715 205]);
add_workspace_sink(modelName, 'Burned or burning cell count', ...
    'burned_cell_count_log', [555 225 715 255]);
add_workspace_sink(modelName, 'Next-ignition risk map', ...
    'next_ignition_risk_map_log', [750 500 910 530]);
